INSERT INTO orders (customer_id, order_date, status, total_amount)
SELECT 
    c.id AS customer_id,
    TIMESTAMP '2024-01-01' + (random() * 700)::int * INTERVAL '1 day' + (random() * 86400)::int * INTERVAL '1 second' AS order_date,
    (ARRAY['новый', 'в обработке', 'отправлен', 'доставлен', 'отменен'])[floor(random() * 5 + 1)::int] AS status,
    (random() * 50000 + 500)::numeric(10,2) AS total_amount
FROM generate_series(1, 800)
CROSS JOIN LATERAL (
    SELECT id FROM customers ORDER BY random() LIMIT 1
) c;

INSERT INTO order_items (order_id, product_id, quantity, price)
SELECT 
    o.id,
    p.id,
    floor(random() * 4 + 1)::int AS quantity,
    p.price
FROM orders o
JOIN products p ON p.id = ((o.id - 1) % 80) + 1
WHERE o.id % 2 = 0;

UPDATE orders o
SET total_amount = sub.total
FROM (
    SELECT order_id, SUM(quantity * price) AS total
    FROM order_items
    GROUP BY order_id
) sub
WHERE o.id = sub.order_id;